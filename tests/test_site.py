from datetime import date, datetime, timezone

import pytest

from newsroom import __main__ as cli
from newsroom.agents.critic import Issue
from newsroom.config import Config
from newsroom.record import EditionRecord, FactRecord, FetchStats, StoryRecord, load_record, save_record
from newsroom.site import build_site, from_markdown, load_editions, load_eval, run_log, safe_url

CONFIG = Config.model_validate({
    "topic": "AI",
    "feeds": [{"name": "TechCrunch AI", "url": "https://techcrunch.com/feed/"}],
    "site": {"title": "Morning Context", "base_url": "https://me.github.io/ai-newsroom/",
             "repo_url": "https://github.com/me/ai-newsroom", "schedule": "Daily · 07:07 PKT", "timezone": "UTC"},
})

LEGACY_MD = """# AI briefing · Thursday 22 October 2026

> Walmart opens up to AI shoppers.

## 1. Walmart Launches Agent Gateway

Walmart has introduced an Agent Gateway.

**Why it matters:** Agents can now shop at a big retailer.

Source: [TechCrunch AI](https://techcrunch.com/walmart) · <sub>6 facts checked against the article · ✓ critic approved</sub>

## 2. TorchTPU Arrives

A native PyTorch backend for TPUs.

Source: [Hugging Face Blog](https://huggingface.co/blog/torchtpu) · <sub>5 facts checked against the article · ✓ approved after 2 rewrites</sub>

<sub>Chosen from 33 stories · 11 facts verified against their sources, 1 unsupported facts removed · critic checked 9 sentences, 1 story rewritten · generated by ai-newsroom</sub>
"""


def record(day=date(2026, 10, 23), title="Model <b>tops</b> & wins", url="https://example.com/a") -> EditionRecord:
    return EditionRecord(
        day=day, started=datetime(2026, 10, 23, 2, 7, 0, tzinfo=timezone.utc), topic="AI", model="gemini/test",
        one_line="A focused day.", candidates=40, critic_rounds=2,
        fetch=FetchStats(fetched=214, unique=163, feeds_ok=5, feeds_total=6, per_feed={"TechCrunch AI": 12}, seconds=4),
        seconds={"editor": 6, "researcher": 30, "writer": 10, "critic": 12},
        stories=[
            StoryRecord(id="a1", title=title, summary="It beats rivals.", why_it_matters="Cheaper coding help.", url=url,
                        source="Lab blog", domain="example.com", is_paper=False, text_source="article",
                        status="rewritten", rewrites=1, sentences_checked=4,
                        facts=[FactRecord(claim="It tops the board", quote="tops the leaderboard")],
                        first_issues=[Issue(text="$9 billion", problem="number not found in the verified facts", by="numbers")]),
            StoryRecord(id="b2", title="A paper", summary="Results.", why_it_matters="", url="https://arxiv.org/abs/1",
                        source="arXiv cs.CL", domain="arxiv.org", is_paper=True, text_source="feed abstract",
                        status="approved", sentences_checked=3,
                        facts=[FactRecord(claim="c1", quote="q1"), FactRecord(claim="c2", quote="q2")]),
        ],
    )


def test_record_round_trip(tmp_path):
    rec = record()
    path = save_record(rec, tmp_path)
    assert path.name == "2026-10-23.json"
    back = load_record(path)
    assert back == rec
    assert back.facts_verified == 3 and back.rewritten == 1 and back.issues_caught == 1
    assert back.total_seconds == 62  # fetch 4 + 58


def test_brief_command_writes_the_json_record(tmp_path, rss_bytes, atom_bytes, monkeypatch):
    from fakes import NewsroomLLM, fake_reader
    from newsroom.sources import parse_feed

    fake = parse_feed(rss_bytes, "RSS") + parse_feed(atom_bytes, "Atom")
    monkeypatch.setattr(cli, "collect", lambda config: (fake, {"RSS": 4, "Atom": 2}))
    monkeypatch.setattr(cli, "make_llm", lambda config: NewsroomLLM())
    monkeypatch.setattr(cli, "make_reader", lambda: fake_reader)
    (tmp_path / "config.yaml").write_text("topic: AI\nfeeds:\n  - {name: RSS, url: 'https://e.com/rss'}\n")
    out = tmp_path / "editions"
    assert cli.main(["brief", "--out", str(out), "--data", str(tmp_path / "data"), "--config", str(tmp_path / "config.yaml")]) == 0

    rec = load_record(next(out.glob("*.json")))
    assert rec.fetch.fetched == len(fake) and rec.fetch.per_feed == {"RSS": 4, "Atom": 2}
    assert rec.started is not None and rec.stories and all(s.facts for s in rec.stories)
    assert any(s.first_issues for s in rec.stories)  # the fake writer plants an error the critic catches


def test_legacy_markdown_is_read_back():
    import tempfile
    from pathlib import Path

    with tempfile.TemporaryDirectory() as d:
        p = Path(d) / "2026-10-22.md"
        p.write_text(LEGACY_MD, encoding="utf-8")
        ed = from_markdown(p, date(2026, 10, 22))
    assert ed.one_line == "Walmart opens up to AI shoppers."
    assert [s.title for s in ed.stories] == ["Walmart Launches Agent Gateway", "TorchTPU Arrives"]
    assert ed.stories[0].why == "Agents can now shop at a big retailer." and ed.stories[1].why == ""
    assert ed.stories[0].url == "https://techcrunch.com/walmart" and ed.stories[0].summary == "Walmart has introduced an Agent Gateway."
    assert [s.status for s in ed.stories] == ["approved", "rewritten"] and ed.stories[1].rewrites == 2
    assert ed.facts_verified == 11 and ed.candidates == 33 and ed.sentences == 9 and ed.dropped == 1
    assert ed.total_seconds is None


def test_json_wins_over_markdown_and_editions_are_numbered(tmp_path):
    (tmp_path / "2026-10-22.md").write_text(LEGACY_MD, encoding="utf-8")
    (tmp_path / "2026-10-23.md").write_text("# ignored, the JSON is used\n", encoding="utf-8")
    (tmp_path / "README.md").write_text("archive", encoding="utf-8")
    save_record(record(), tmp_path)
    eds = load_editions(tmp_path)
    assert [(e.number, e.day.day, e.record is not None) for e in eds] == [(1, 22, False), (2, 23, True)]


def test_run_log_uses_real_stage_times_and_flags_catches():
    from newsroom.site import from_record

    lines = run_log(from_record(record()), timezone.utc)
    assert lines[0] == ("02:07:04", "sources", "Fetched 5 of 6 feeds · 214 stories", "")
    assert ("02:07:10", "editor", "Ranked 40 candidates, picked 2", "") in lines
    warn = [m for _, ag, m, kind in lines if kind == "warn"]
    assert warn == ["Story 1: “$9 billion” number not found in the verified facts"]
    assert lines[-1] == ("02:08:02", "publish", "Committed editions/2026-10-23.md", "good")


def test_build_site(tmp_path):
    eds, evals, out = tmp_path / "editions", tmp_path / "evals", tmp_path / "site"
    eds.mkdir(), evals.mkdir()
    (eds / "2026-10-22.md").write_text(LEGACY_MD, encoding="utf-8")
    save_record(record(url="javascript:alert(1)"), eds)
    (evals / "results-2026-10-22.md").write_text(
        "# Critic evaluation\n\nModel: `gemini/x`\n\n- **Planted errors caught: 8 of 8**\n  - by the number check (code): 2\n"
        "  - by the AI critic: 7\n- **False alarms on clean drafts: 0 of 5**\n\n| Case | Kind | Planted error | Result | What the critic flagged |\n"
        "|---|---|---|---|---|\n| c1 | number | 95 percent | caught | “95 percent” (numbers) |\n", encoding="utf-8")

    build_site(CONFIG, eds, evals, out)
    names = {p.relative_to(out).as_posix() for p in out.rglob("*") if p.is_file()}
    assert {"index.html", "archive.html", "sources.html", "how-it-works.html", "feed.xml", "style.css", ".nojekyll",
            "editions/2026-10-22.html", "editions/2026-10-23.html"} <= names

    index = (out / "index.html").read_text(encoding="utf-8")
    assert "Run #2" in index and "Morning Context" in index and "Issue 2" in index
    assert "Model &lt;b&gt;tops&lt;/b&gt; &amp; wins" in index and "<b>tops</b>" not in index  # escaped
    assert 'href="#" rel="noopener">Source: Lab blog' in index                             # unsafe link dropped
    assert "214" in index and "1m 02s" in index and "tops the leaderboard" in index
    assert 'href="style.css"' in index and 'href="editions/2026-10-22.html"' in index

    old = (out / "editions/2026-10-22.html").read_text(encoding="utf-8")
    assert 'href="../style.css"' in old and "written before v0.6" in old and "Approved after 2 rewrites" in old

    archive = (out / "archive.html").read_text(encoding="utf-8")
    assert archive.index("2026-10-23.html") < archive.index("2026-10-22.html")  # newest first
    how = (out / "how-it-works.html").read_text(encoding="utf-8")
    assert "8/8" in how and "0/5" in how and "2 + 7" in how and "gemini/x" in how
    assert "<link>https://me.github.io/ai-newsroom/editions/2026-10-23.html</link>" in (out / "feed.xml").read_text()

    build_site(CONFIG, eds, evals, out)  # rebuilding replaces its own output


def test_build_refuses_a_folder_it_did_not_make(tmp_path):
    (tmp_path / "notes.txt").write_text("mine")
    with pytest.raises(FileExistsError):
        build_site(CONFIG, tmp_path / "editions", tmp_path / "evals", tmp_path)
    assert (tmp_path / "notes.txt").exists()


def test_empty_site_and_missing_eval(tmp_path):
    build_site(CONFIG, tmp_path / "none", tmp_path / "none", tmp_path / "site")
    assert "No editions yet" in (tmp_path / "site/index.html").read_text(encoding="utf-8")
    assert load_eval(tmp_path / "none") is None


def test_site_command(tmp_path, capsys):
    (tmp_path / "config.yaml").write_text("topic: AI\nfeeds:\n  - {name: RSS, url: 'https://e.com/rss'}\n")
    eds = tmp_path / "editions"
    eds.mkdir()
    (eds / "2026-10-22.md").write_text(LEGACY_MD, encoding="utf-8")
    args = ["site", "--editions", str(eds), "--evals", str(tmp_path / "evals"), "--out", str(tmp_path / "site"),
            "--config", str(tmp_path / "config.yaml")]
    assert cli.main(args) == 0
    assert "Built" in capsys.readouterr().out


def test_safe_url():
    assert safe_url("https://a.com/x") == "https://a.com/x"
    assert safe_url("javascript:alert(1)") == "#" and safe_url("") == "#"
