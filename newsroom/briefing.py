"""Choosing candidates and turning a finished briefing into a Markdown edition."""

from __future__ import annotations

from collections import defaultdict
from datetime import date
from pathlib import Path

from .agents.researcher import FactSheet
from .agents.writer import Briefing
from .dedupe import strip_tracking
from .models import Story


def select_candidates(stories: list[Story], max_total: int = 40, max_per_source: int = 8) -> list[Story]:
    """Newest first, taken round-robin across sources so one busy feed (arXiv) can't crowd out the rest."""
    by_source: dict[str, list[Story]] = defaultdict(list)
    for s in sorted(stories, key=lambda s: s.published.timestamp() if s.published else 0, reverse=True):
        if len(by_source[s.source]) < max_per_source:
            by_source[s.source].append(s)
    picked: list[Story] = []
    queues = list(by_source.values())
    while queues and len(picked) < max_total:
        for q in list(queues):
            if q:
                picked.append(q.pop(0))
                if len(picked) == max_total:
                    break
            if not q:
                queues.remove(q)
    return picked


STATUS_TEXT = {
    "approved": "✓ critic approved",
    "rewritten": "✓ approved after {n} rewrite{s}",
    "facts-only": "⚠ draft failed fact-check; showing verified facts only",
    "numbers-only": "◐ numbers checked (AI critic unavailable)",
    "unchecked": "not reviewed by the critic",
}


def status_text(result) -> str:
    if result is None:
        return ""
    n = result.rewrites
    return STATUS_TEXT[result.status].format(n=n, s="" if n == 1 else "s")


def render_markdown(briefing: Briefing, sheets: list[FactSheet], topic: str, day: date, candidates: int,
                    results: list | None = None) -> str:
    by_id = {s.story.id: s for s in sheets}
    res = {r.story_id: r for r in (results or [])}
    out = [f"# {topic} briefing · {day:%A %d %B %Y}", "", f"> {briefing.one_line}", ""]
    for i, item in enumerate(briefing.items, 1):
        sheet = by_id[item.story_id]
        story = sheet.story
        checked_against = "abstract" if "abstract" in sheet.text_source else sheet.text_source
        badge = status_text(res.get(item.story_id))
        out += [f"## {i}. {item.title}", "", item.summary, ""]
        if item.why_it_matters:
            out += [f"**Why it matters:** {item.why_it_matters}", ""]
        out += [
            f"Source: [{story.display_source}]({strip_tracking(str(story.url))}) · "
            f"<sub>{len(sheet.facts)} facts checked against the {checked_against}"
            + (f" · {badge}" if badge else "") + "</sub>",
            "",
        ]

    facts = sum(len(s.facts) for s in sheets)
    dropped = sum(len(s.dropped) for s in sheets)
    footer = f"Chosen from {candidates} stories · {facts} facts verified against their sources"
    if dropped:
        footer += f", {dropped} unsupported facts removed"
    if results:
        sentences = sum(r.sentences_checked for r in results)
        rewritten = sum(1 for r in results if r.status == "rewritten")
        fallback = sum(1 for r in results if r.status == "facts-only")
        footer += f" · critic checked {sentences} sentences"
        if rewritten:
            footer += f", {rewritten} stor{'y' if rewritten == 1 else 'ies'} rewritten"
        if fallback:
            footer += f", {fallback} shown as facts only"
    out.append(f"<sub>{footer} · generated by ai-newsroom</sub>")
    return "\n".join(out) + "\n"


def save_edition(markdown: str, day: date, out_dir: str | Path = "editions") -> Path:
    path = Path(out_dir) / f"{day.isoformat()}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(markdown, encoding="utf-8")
    return path
